const en: Dict = { ...coreEn, ...formsEn, ...estEn, ...analyticsEn };
const om: Dict = { ...coreOm, ...formsOm, ...estOm, ...analyticsOm };

const DICTS: Record<Lang, Dict> = { en, om };

export type TFunction = (key: string, vars?: Record<string, string | number>) => string;

const translate = (lang: Lang, key: string, vars?: Record<string, string | number>) => {
  // "v.<English literal>" keys fall back to the literal itself when untranslated.
  const fallback = key.startsWith("v.") ? key.slice(2) : key;
  const template = DICTS[lang][key] ?? en[key] ?? fallback;
  if (!vars) return template;
  return Object.entries(vars).reduce((acc, [k, v]) => acc.replaceAll(`{${k}}`, String(v)), template);
};

const LangContext = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: TFunction }>({
  lang: "en",
  setLang: () => {},
  t: (k, v) => translate("en", k, v),
});

const STORAGE_KEY = "mn-registry-lang";

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");

  useEffect(() => {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    if (stored === "en" || stored === "om") setLangState(stored);
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang === "om" ? "om" : "en";
  }, [lang]);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    window.localStorage.setItem(STORAGE_KEY, l);
  }, []);

  const t = useCallback<TFunction>((key, vars) => translate(lang, key, vars), [lang]);

  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);
  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export function useI18n() {
  return useContext(LangContext);
}

/** Convenience: just the translate function. */
export function useT(): TFunction {
  return useContext(LangContext).t;
}
